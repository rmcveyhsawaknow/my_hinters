"""Generate the thin per-agent GitHub Actions callers from personas.

One caller per persona (``.github/workflows/agent-<slug>.yml``) with its own crons, a
``workflow_dispatch`` dry-run option, explicit secrets only, and a guard on
``vars.HG_ENABLED`` and ``vars.HG_AGENT_<AGENT>``. ``hglab sync --check`` fails when a
persona lacks a caller, a caller lacks a persona, or a caller is stale.
"""

from __future__ import annotations

import re
from pathlib import Path

from hglab.persona import Persona, list_persona_slugs, load_persona

CALLER_PREFIX = "agent-"
REUSABLE = "_agent.yml"
HEADER = "# Generated by `hglab sync` from agents/{slug}/persona.md. Edit the persona, then run `hglab sync`.\n"


def keepalive_cron(persona: Persona) -> str:
    minute = int(persona.knobs["cadence"]["cron"].split()[0].split(",")[0])
    return f"{(minute + 30) % 60} */6 * * *"


def pulse_cron(persona: Persona) -> str:
    minute = int(persona.knobs["cadence"]["cron"].split()[0].split(",")[0])
    return f"{(minute + 15) % 60} 5 * * *"


def retro_cron(persona: Persona) -> str:
    minute = int(persona.knobs["cadence"]["cron"].split()[0].split(",")[0])
    return f"{(minute + 45) % 60} 6 * * 0"


def work_cron(persona: Persona) -> str | None:
    work = persona.knobs.get("work")
    return str(work["cron"]) if work else None


def caller_text(persona: Persona) -> str:
    tick = persona.knobs["cadence"]["cron"]
    keepalive = keepalive_cron(persona)
    pulse = pulse_cron(persona)
    retro = retro_cron(persona)
    work = work_cron(persona)
    secret = persona.secret_name
    variable = persona.variable_name
    jitter = int(persona.knobs["cadence"]["jitter_minutes"])
    job_expr = (
        "${{ github.event_name == 'workflow_dispatch' && inputs.job"
        f" || (github.event.schedule == '{tick}' && 'tick')"
        f" || (github.event.schedule == '{pulse}' && 'pulse')"
        f" || (github.event.schedule == '{retro}' && 'retro')"
        + (f" || (github.event.schedule == '{work}' && 'shift')" if work else "")
        + " || 'keepalive' }}"
    )
    work_line = f"    - cron: \"{work}\"  # work shift: deterministic building and gathering\n" if work else ""
    return (
        HEADER.format(slug=persona.slug)
        + f"name: Agent {persona.name}\n\n"
        "on:\n"
        "  schedule:\n"
        f"    - cron: \"{tick}\"  # persona wake\n"
        f"    - cron: \"{keepalive}\"  # keepalive: verification never lapses\n"
        f"    - cron: \"{pulse}\"  # daily pulse\n"
        f"    - cron: \"{retro}\"  # weekly retrospective proposal\n"
        + work_line
        + "  workflow_dispatch:\n"
        "    inputs:\n"
        "      job:\n"
        "        description: Which job to run\n"
        "        type: choice\n"
        "        options: [keepalive, tick, pulse, retro, shift]\n"
        "        default: tick\n"
        "      dry_run:\n"
        "        description: Plan without acting (tick only)\n"
        "        type: boolean\n"
        "        default: true\n\n"
        "permissions:\n"
        "  contents: read\n\n"
        "concurrency:\n"
        f"  group: hg-agent-{persona.slug}\n"
        "  cancel-in-progress: false\n\n"
        "jobs:\n"
        "  agent:\n"
        f"    if: vars.HG_ENABLED == 'true' && vars.{variable} == 'on' && (github.event_name == 'workflow_dispatch' || github.ref_name == github.event.repository.default_branch)\n"
        f"    uses: ./.github/workflows/{REUSABLE}\n"
        "    permissions:\n"
        "      contents: write\n"
        "      pull-requests: write\n"
        "    with:\n"
        f"      agent: {persona.slug}\n"
        f"      job: {job_expr}\n"
        "      dry_run: ${{ github.event_name == 'workflow_dispatch' && inputs.dry_run || false }}\n"
        f"      jitter_minutes: {jitter}\n"
        "    secrets:\n"
        f"      hg_key: ${{{{ secrets.{secret} }}}}\n"
        "      anthropic_api_key: ${{ secrets.ANTHROPIC_API_KEY }}\n"
        "      openai_api_key: ${{ secrets.OPENAI_API_KEY }}\n"
    )


def caller_path(root: Path, slug: str) -> Path:
    return root / ".github/workflows" / f"{CALLER_PREFIX}{slug}.yml"


def existing_callers(root: Path) -> dict[str, Path]:
    folder = root / ".github/workflows"
    out: dict[str, Path] = {}
    for path in sorted(folder.glob(f"{CALLER_PREFIX}*.yml")):
        slug = path.stem.removeprefix(CALLER_PREFIX)
        if re.fullmatch(r"[a-z][a-z0-9-]{1,30}", slug):
            out[slug] = path
    return out


def generate_callers(root: Path, *, check: bool = False) -> tuple[list[str], list[str]]:
    """Write (or check) every caller. Returns (written_or_current, problems)."""
    problems: list[str] = []
    done: list[str] = []
    slugs = list_persona_slugs(root)
    for slug in slugs:
        persona = load_persona(root, slug)
        target = caller_path(root, slug)
        text = caller_text(persona)
        if check:
            if not target.exists():
                problems.append(f"persona {slug} has no caller workflow ({target.relative_to(root).as_posix()})")
            elif target.read_text(encoding="utf-8") != text:
                problems.append(f"caller workflow for {slug} is stale; run `hglab sync`")
            else:
                done.append(target.relative_to(root).as_posix())
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8", newline="\n")
            done.append(target.relative_to(root).as_posix())
    for slug, path in existing_callers(root).items():
        if slug not in slugs:
            problems.append(f"caller {path.relative_to(root).as_posix()} has no persona; delete it or add agents/{slug}/persona.md")
    if not (root / ".github/workflows" / REUSABLE).exists():
        problems.append(f".github/workflows/{REUSABLE} is missing")
    return done, problems


__all__ = ["caller_path", "caller_text", "existing_callers", "generate_callers", "keepalive_cron", "pulse_cron", "retro_cron", "work_cron"]
